def load_registry_cards(cards_dir: pathlib.Path):
    """(optional) registry/cards.yaml: {..., cards: [{id, headline, members: [...], ...}, ...]} —
    the Phase-1 plan of which declarations each future card covers, for the README coverage
    count. None if the file is absent (nothing to compare against yet)."""
    path = cards_dir / "registry" / "cards.yaml"
    if not path.exists():
        return None
    require_yaml()
    with open(path, encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    return data


def planned_decls_from_registry(registry) -> set[str]:
    """The declarations `registry/cards.yaml` plans to cover, regardless of whether a card for
    them exists yet. Accepts either shape seen for this (small, hand-maintained, still settling)
    registry: a flat `{id: {planned: [...], headline, members, ...}}` mapping, or `{cards: [{id,
    headline, members, ...}, ...]}`. Prefers an entry's explicit `planned` list; falls back to
    `headline` + `members` when absent, so a card entry cannot silently contribute zero decls."""
    planned: set[str] = set()
    if not isinstance(registry, dict):
        return planned
    if isinstance(registry.get("cards"), list):
        entries = [e for e in registry["cards"] if isinstance(e, dict)]
    else:
        entries = [v for v in registry.values() if isinstance(v, dict)]
    for entry in entries:
        if entry.get("planned"):
            for d in entry["planned"]:
                planned.add(d)
            continue
        if entry.get("headline"):
            planned.add(entry["headline"])
        for m in entry.get("members") or []:
            planned.add(m)
    return planned


def write_readme_and_open_items(cards_dir: pathlib.Path, cards: list[tuple[pathlib.Path, dict]],
                                 catalog: dict, scope_tags, scope_pub):
    by_frontier: dict[str, list[str]] = defaultdict(list)
    by_published: dict[str, list[str]] = defaultdict(list)
    by_pipeline: dict[str, list[str]] = defaultdict(list)
    covered_decls: set[str] = set()

    lines_ro = ["# Theorem cards", "",
                "> **AUTO-GENERATED** by `scripts/gen_cards.py` from `docs/theorems/*.md` "
                "front matter — do not hand-edit; the docs-sync CI gate diffs this "
                "against source.", ""]
    for path, fm in cards:
        cid = fm.get("id", path.stem)
        status = fm.get("status") or {}
        for fid in (fm.get("frontier") or {}).get("ids", []) if isinstance(fm.get("frontier"), dict) else []:
            by_frontier[fid].append(cid)
        # `scope.*` is never authored (SCHEMA.md: generated-only) — derive the headline's
        # published tag the same way the Facts block does, from the catalog + scope-tags.tsv /
        # scope-published.tsv, not from a nonexistent front-matter field.
        pub = "UNKNOWN"
        decl = (fm.get("lean") or {}).get("decl")
        resolved, _c = resolve_name(decl, catalog) if decl else (None, [])
        if resolved:
            rec = catalog[resolved]
            row = scope_row(rec, scope_tags)
            prow = published_row(rec, scope_pub)
            if prow:
                pub = prow[2]  # (kind, own, published, via)
            elif row:
                pub = row[0]
        by_published[pub].append(cid)
        by_pipeline[status.get("pipeline", "UNKNOWN")].append(cid)
        for _label, name in ordered_decls(fm):
            covered_decls.add(name)

    lines_ro.append("## By frontier id")
    lines_ro.append("")
    for fid in sorted(by_frontier):
        ids = ", ".join(f"[`{c}`]({c}.md)" for c in sorted(by_frontier[fid]))
        lines_ro.append(f"- **{fid}**: {ids}")
    lines_ro.append("")
    lines_ro.append("## By published scope tag")
    lines_ro.append("")
    for tag in sorted(by_published):
        ids = ", ".join(f"[`{c}`]({c}.md)" for c in sorted(by_published[tag]))
        lines_ro.append(f"- **{tag}**: {ids}")
    lines_ro.append("")
    lines_ro.append("## By pipeline status")
    lines_ro.append("")
    for status in sorted(by_pipeline):
        ids = ", ".join(f"[`{c}`]({c}.md)" for c in sorted(by_pipeline[status]))
        lines_ro.append(f"- **{status}**: {ids}")
    lines_ro.append("")

    registry = load_registry_cards(cards_dir)
    lines_ro.append("## Coverage")
    lines_ro.append("")
    if registry is None:
        lines_ro.append("`docs/theorems/registry/cards.yaml` not found — planned-declaration "
                         "coverage is not tracked yet (advisory only; see `--require-coverage` "
                         "in `scripts/check_cards.py`).")
    else:
        planned = planned_decls_from_registry(registry)
        missing = sorted(planned - covered_decls)
        lines_ro.append(f"{len(planned) - len(missing)}/{len(planned)} planned declarations have "
                         f"a card ({len(cards)} cards, {len(covered_decls)} declarations "
                         f"covered).")
        if missing:
            lines_ro.append("")
            lines_ro.append("Not yet covered by any card:")
            lines_ro.append("")
            for d in missing:
                lines_ro.append(f"- `{d}`")
    lines_ro.append("")
    (cards_dir / "README.md").write_text("\n".join(lines_ro) + "\n", encoding="utf-8")

    lines_oi = ["# Open items", "",
                "> **AUTO-GENERATED** by `scripts/gen_cards.py`: every card's `open_items`, "
                "rolled up. cflibs-formal has no `.beads/`; this plus optional issue links is "
                "the tracker (IA-proposal §1.3 item 4).", ""]
    any_items = False
    for path, fm in cards:
        cid = fm.get("id", path.stem)
        items = fm.get("open_items") or []
        if not items:
            continue
        any_items = True
        lines_oi.append(f"## [`{cid}`]({cid}.md)")
        lines_oi.append("")
        for item in items:
            if isinstance(item, dict):
                kind = item.get("kind", "?")
                text = item.get("text", "")
                ref = f" ({item['ref']})" if item.get("ref") else ""
                lines_oi.append(f"- **{kind}**: {text}{ref}")
            else:
                lines_oi.append(f"- {item}")
        lines_oi.append("")
    if not any_items:
        lines_oi.append("*(no open items on any card)*")
        lines_oi.append("")
    (cards_dir / "open-items.md").write_text("\n".join(lines_oi) + "\n", encoding="utf-8")


# ---------------------------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=pathlib.Path,
                     default=pathlib.Path(__file__).resolve().parent.parent)
    ap.add_argument("--catalog", type=pathlib.Path, default=None)
    ap.add_argument("--cards-dir", type=pathlib.Path, default=None)
    ap.add_argument("--stamp", metavar="ID", default=None,
                     help="stamp docs/theorems/<ID>.md's reviewed.statement_hash + commit, then "
                          "exit (does not regenerate facts blocks or README/open-items.md)")
    args = ap.parse_args(argv)

    root = args.root.resolve()
    catalog_path = args.catalog or (root / "docs" / "catalog.jsonl")
    cards_dir = args.cards_dir or (root / "docs" / "theorems")

    if not catalog_path.exists():
        print(f"gen_cards: catalog not found: {catalog_path}", file=sys.stderr)
        return 1
    catalog = load_catalog(catalog_path)

    if args.stamp:
        card_path = cards_dir / f"{args.stamp}.md"
        if not card_path.exists():
            print(f"gen_cards: no such card: {card_path}", file=sys.stderr)
            return 1
        try:
            new_hash, sha = stamp_card(card_path, catalog, root)
        except CardError as e:
            print(f"gen_cards: --stamp {args.stamp}: {e}", file=sys.stderr)
            return 1
        print(f"gen_cards: stamped {card_path} -> statement_hash={new_hash} commit={sha}")
        return 0

    scope_tags = load_scope_tags(root / "docs" / "scope-tags.tsv")
    scope_pub = load_scope_published(root / "docs" / "scope-published.tsv")
    whitelist = load_whitelist(root / "docs" / "citation-whitelist.tsv")
    used_by = build_used_by(catalog)

    changed = 0
    failed: list[str] = []
    cards: list[tuple[pathlib.Path, dict]] = []
    for path in iter_card_paths(cards_dir):
        try:
            fm, _body, _fm_text = load_card(path)
        except CardError as e:
            failed.append(f"{path}: {e}")
            continue
        cards.append((path, fm))
        try:
            if regenerate_card_facts(path, catalog, scope_tags, scope_pub, whitelist, used_by):
                changed += 1
        except CardError as e:
            failed.append(f"{path}: {e}")

    write_readme_and_open_items(cards_dir, cards, catalog, scope_tags, scope_pub)

    print(f"gen_cards: {len(cards)} card(s) processed, {changed} facts block(s) changed, "
          f"README.md + open-items.md written to {cards_dir}")
    if failed:
        for msg in failed:
            print(f"gen_cards: FAILED {msg}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
